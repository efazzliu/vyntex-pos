import type { AdminUserMetadata } from "./admin-settings-types.ts";

export type AdminLang = "en" | "sq" | "de" | "fr";

const STORAGE_KEY = "vyntex-admin-lang";

export function normalizeAdminLang(raw?: string | null): AdminLang {
  if (raw === "sq" || raw === "de" || raw === "fr" || raw === "en") return raw;
  return "en";
}

export function localeTag(lang: AdminLang): string {
  if (lang === "sq") return "sq-AL";
  if (lang === "de") return "de-DE";
  if (lang === "fr") return "fr-FR";
  return "en-GB";
}

export function applyAdminLanguage(lang: AdminLang) {
  if (typeof document === "undefined") return;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = localeTag(lang);
}

export function readStoredAdminLang(): AdminLang | null {
  if (typeof window === "undefined") return null;
  const v = localStorage.getItem(STORAGE_KEY);
  return v === "en" || v === "sq" || v === "de" || v === "fr" ? v : null;
}

